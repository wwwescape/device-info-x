/** Emoji -> lowercase searchable keyword, built by pairing each EMOJI_CATEGORIES list with its
 * same-order keyword list above by position — see the block comment above [SMILEYS_KEYWORDS] for
 * why it's done this way rather than keying directly off retyped emoji literals. If a category's
 * keyword list ends up shorter than its emoji list (a mismatch introduced by future hand-editing),
 * zip() just silently leaves the extra trailing emoji unsearchable rather than crashing. */
val EMOJI_KEYWORDS: Map<String, String> = buildMap {
    fun addCategory(category: EmojiCategory, keywords: List<String>) {
        EMOJI_CATEGORIES[category].orEmpty().zip(keywords).forEach { (emoji, keyword) -> put(emoji, keyword) }
    }
    addCategory(EmojiCategory.SMILEYS, SMILEYS_KEYWORDS)
    addCategory(EmojiCategory.PEOPLE, PEOPLE_KEYWORDS)
    addCategory(EmojiCategory.ANIMALS, ANIMALS_KEYWORDS)
    addCategory(EmojiCategory.FOOD, FOOD_KEYWORDS)
    addCategory(EmojiCategory.TRAVEL, TRAVEL_KEYWORDS)
    addCategory(EmojiCategory.ACTIVITIES, ACTIVITIES_KEYWORDS)
    addCategory(EmojiCategory.OBJECTS, OBJECTS_KEYWORDS)
    addCategory(EmojiCategory.SYMBOLS, SYMBOLS_KEYWORDS)
    addCategory(EmojiCategory.FLAGS, FLAGS_KEYWORDS)
}
